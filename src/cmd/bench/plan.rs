/// `gen::generate`'s arguments for the trie: lines, template families and seed. Family
/// count is not template count; these three give exactly `TEMPLATES`.
pub const TRIE_LINES: u64 = 11_661;
pub const TRIE_FAMILIES: usize = 2_000;
pub const TRIE_SEED: u64 = 42;
/// Templates the trie must hold. Any other count means the generator or the promotion
/// rule moved, and the timings would be of another trie.
pub const TEMPLATES: u64 = 10_000;
/// Where the trie came from, as a result records it.
pub const TRIE_SOURCE: &str =
    "gen::generate(lines 11661, templates 2000, seed 42) through Trie::ingest";

/// The four shapes: the measuring script's texts, byte for byte. `P2` is the table's plan
/// step - a key most templates hold and none is filed under, which is the shape a map
/// from a key to its templates is for.
pub const P1: &str = r#"COUNT LOG {"event":"login_ok"}"#;
pub const P2: &str = r#"COUNT LOG {"level":"error"}"#;
pub const P3: &str = r#"MATCH LOG {"err.trace_id":"aeb53b34-0c10-4971-8a69-db9873af8965"}"#;
pub const P4: &str = "MATCH LOG {} LIMIT 500";

/// The four shapes with their labels.
pub fn queries() -> Shapes<QueryText> {
    let query = |label: &str, text: &str| QueryText {
        label: label.to_string(),
        text: text.to_string(),
    };
    Shapes {
        p1: query("promoted value", P1),
        p2: query("unpromoted key", P2),
        p3: query("one id", P3),
        p4: query("newest 500", P4),
    }
}

/// The command the child is, as an error names it.
const CHILD: &str = "kibbr bench --plan-only";

/// Lines of its standard error an error quotes: the last of them is what stopped it, under
/// hundreds of warnings from the building of the trie.
const CHILD_TAIL: usize = 20;

/// Plan children this process has started, so that each one's standard error has a file of
/// its own: a unit that was disturbed is done again, and the first one's file stays.
static CHILDREN: AtomicUsize = AtomicUsize::new(0);

/// The one instant every line of the trie arrives at and every shape is parsed at: the
/// arrival time of the whole bench, so that nothing here reads the clock on the wall.
fn arrival() -> DateTime<Utc> {
    DateTime::parse_from_rfc3339(RECEIVED_AT)
        .expect("RECEIVED_AT is an RFC 3339 instant")
        .with_timezone(&Utc)
}

/// The trie, and the generated lines the parser refused - which are in no template, as
/// they would be in none through the command line.
///
/// The generated bytes are dropped before this returns: the plans are timed in a heap
/// that holds the trie and nothing else.
fn build(now: DateTime<Utc>) -> Result<(Trie, u64), SpeedError> {
    let mut lines = Vec::new();
    gen::generate(&mut lines, TRIE_LINES, TRIE_FAMILIES, TRIE_SEED).map_err(|e| {
        SpeedError::Corpus(format!(
            "the plan step's trie could not be generated ({TRIE_SOURCE}): {}",
            error::chain(&e)
        ))
    })?;
    let trie = Trie::new().with_time_columns(TIME_COLUMNS.map(String::from).to_vec());
    let mut skipped = 0;
    // Every line ends in a line feed, so what follows the last one is not a line.
    let text = lines.strip_suffix(b"\n").unwrap_or(&lines);
    for (at, line) in text.split(|byte| *byte == b'\n').enumerate() {
        let Ok(parsed) = flatten::parse_line(line, at + 1) else {
            skipped += 1;
            continue;
        };
        trie.ingest(&parsed, now).map_err(|e| {
            SpeedError::Corpus(format!(
                "the plan step's trie could not take line {} of {TRIE_SOURCE}: {}",
                at + 1,
                error::chain(&e)
            ))
        })?;
    }
    Ok((trie, skipped))
}

/// One shape: the unmeasured plans, then `samples` timed ones.
///
/// A timing is the call and nothing else. The vectors are sized beforehand, so nothing of
/// the bench's own allocates between two plans, and each plan is dropped only after its
/// clock has stopped - freeing thousands of leaves is not planning.
fn time(
    name: &'static str,
    trie: &Trie,
    query: &Query,
    samples: usize,
) -> Result<PlanShape, SpeedError> {
    for _ in 0..plan_warmup(samples) {
        drop(black_box(engine::plan(trie, query)));
    }
    let mut ms = Vec::with_capacity(samples);
    let mut leaves = Vec::with_capacity(samples);
    for _ in 0..samples {
        let started = Instant::now();
        let plan = black_box(engine::plan(trie, query));
        let took = started.elapsed();
        ms.push(took.as_secs_f64() * 1000.0);
        leaves.push(plan.leaves.len() as u64);
        drop(plan);
    }
    shape(name, ms, &leaves)
}

/// What a result keeps of one shape's timings. Every plan of one query on one trie must
/// return the same leaves: a count that moved between two calls is not a number about
/// one plan.
fn shape(name: &'static str, ms: Vec<f64>, leaves: &[u64]) -> Result<PlanShape, SpeedError> {
    let unread = |detail: String| SpeedError::Surface {
        surface: "engine::plan",
        detail,
    };
    let (Some(p50_ms), Some(p99_ms), Some(&first)) =
        (percentile(&ms, 0.50), percentile(&ms, 0.99), leaves.first())
    else {
        return Err(unread(format!(
            "{name} was planned no times, so it has no p50; --samples must be 1 or more"
        )));
    };
    if let Some(other) = leaves.iter().find(|count| **count != first) {
        return Err(unread(format!(
            "{name} planned to {} leaves and then to {} on the same trie",
            commas(first),
            commas(*other)
        )));
    }
    let min_ms = ms.iter().copied().fold(f64::INFINITY, f64::min);
    Ok(PlanShape {
        ms,
        p50_ms,
        p99_ms,
        min_ms,
        leaves: first,
    })
}

/// In this process: build the trie, hold it to `TEMPLATES`, and for each shape time
/// `samples` calls of `engine::plan` after the unmeasured ones. What `--plan-only` runs.
/// Each timing is the call alone: the plan is dropped after the clock has stopped.
pub fn measure(samples: usize) -> Result<PlanRun, SpeedError> {
    let now = arrival();
    let (trie, lines_skipped) = build(now)?;
    let templates = trie.template_count();
    if templates != TEMPLATES {
        return Err(SpeedError::Corpus(format!(
            "the plan step's trie holds {} templates where it must hold {}: the generator \
             or the rule that promotes a value moved, and plans timed on this trie would \
             compare with no saved result ({TRIE_SOURCE})",
            commas(templates),
            commas(TEMPLATES)
        )));
    }

    // Every shape is parsed before the first is timed, so that all four are planned in
    // the same heap.
    let shapes = queries();
    let mut parsed = Vec::with_capacity(Shapes::<()>::NAMES.len());
    for shape in shapes.each() {
        let query = query::from_trieql(&shape.text, now, Limits::default()).map_err(|e| {
            SpeedError::Surface {
                surface: "query::from_trieql",
                detail: format!("{}: {}", shape.text, error::chain(&e)),
            }
        })?;
        parsed.push(query);
    }
    let [p1, p2, p3, p4] = Shapes::<()>::NAMES;
    let [q1, q2, q3, q4] = parsed.as_slice() else {
        return Err(SpeedError::Surface {
            surface: "query::from_trieql",
            detail: "the four shapes did not parse to four queries".to_string(),
        });
    };
    Ok(PlanRun {
        templates,
        nodes: trie.node_count(),
        tokens: trie.token_count(),
        lines_skipped,
        shapes: Shapes {
            p1: time(p1, &trie, q1, samples)?,
            p2: time(p2, &trie, q2, samples)?,
            p3: time(p3, &trie, q3, samples)?,
            p4: time(p4, &trie, q4, samples)?,
        },
    })
}

/// Read what the child printed: one line, the JSON of a `PlanRun`, on the trie every
/// result is measured on and with `samples` timings a shape. Anything else is said in a
/// sentence, for the error that names the child.
pub fn read_line(stdout: &[u8], samples: usize) -> Result<PlanRun, String> {
    let text = std::str::from_utf8(stdout)
        .map_err(|e| format!("its standard output is not UTF-8 ({e})"))?;
    let lines: Vec<&str> = text.lines().collect();
    let [line] = lines.as_slice() else {
        return Err(format!(
            "it printed {} lines where one line of JSON is read",
            lines.len()
        ));
    };
    let run: PlanRun = serde_json::from_str(line)
        .map_err(|e| format!("its line is not the plan step's JSON ({e})"))?;
    if run.templates != TEMPLATES {
        return Err(format!(
            "it planned on a trie of {} templates where the plan step's has {}",
            commas(run.templates),
            commas(TEMPLATES)
        ));
    }
    for (name, shape) in Shapes::<()>::NAMES.iter().zip(run.shapes.each()) {
        if shape.ms.len() != samples {
            return Err(format!(
                "it timed {name} {} times where {samples} were asked for",
                shape.ms.len()
            ));
        }
    }
    Ok(run)
}

/// Run `exe bench --plan-only --samples <samples>` as a child with a scrubbed
/// environment, its standard error in a file under `work`, and read the one line it
/// prints. A child that fails, or prints anything else, is `SpeedError::Child`.
pub fn child(exe: &Path, samples: usize, work: &Path) -> Result<PlanRun, SpeedError> {
    let log = work.join(format!(
        "plan-{}.log",
        CHILDREN.fetch_add(1, Ordering::Relaxed) + 1
    ));
    let stderr = File::create(&log).map_err(|source| SpeedError::Io {
        path: log.clone(),
        source,
    })?;
    let mut command = Command::new(exe);
    command
        .args(["bench", "--plan-only", "--samples"])
        .arg(samples.to_string())
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::from(stderr));
    scrub(&mut command);
    let output = command.output().map_err(|source| SpeedError::Io {
        path: exe.to_path_buf(),
        source,
    })?;

    // The file is read only to quote it; a file that cannot be read quotes nothing.
    let said = || {
        let text = fs::read(&log).unwrap_or_default();
        format!(
            "its standard error is kept in {} and ends:\n{}",
            log.display(),
            tail(&String::from_utf8_lossy(&text), CHILD_TAIL)
        )
    };
    if !output.status.success() {
        return Err(SpeedError::Child {
            what: CHILD,
            code: output.status.code(),
            stderr: said(),
        });
    }
    read_line(&output.stdout, samples).map_err(|wrong| SpeedError::Child {
        what: CHILD,
        code: output.status.code(),
        stderr: format!("{wrong}; {}", said()),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_four_shapes_are_the_texts_a_saved_result_is_compared_on() {
        let shapes = queries();
        let texts: Vec<&str> = shapes.each().iter().map(|q| q.text.as_str()).collect();
        assert_eq!(
            texts,
            [
                r#"COUNT LOG {"event":"login_ok"}"#,
                r#"COUNT LOG {"level":"error"}"#,
                r#"MATCH LOG {"err.trace_id":"aeb53b34-0c10-4971-8a69-db9873af8965"}"#,
                "MATCH LOG {} LIMIT 500",
            ]
        );
        assert_eq!(
            TRIE_SOURCE,
            format!(
                "gen::generate(lines {TRIE_LINES}, templates {TRIE_FAMILIES}, seed \
                 {TRIE_SEED}) through Trie::ingest"
            )
        );
    }

    #[test]
    fn the_trie_holds_exactly_ten_thousand_templates_and_each_shape_plans_to_its_leaves() {
        let run = measure(2).expect("the plan step");
        assert_eq!(
            run.templates, 10_000,
            "the count the plan step is named for"
        );
        assert_eq!((run.nodes, run.tokens), (57_642, 98_495));
        assert_eq!(
            run.lines_skipped, 0,
            "the generator writes no line the parser refuses"
        );
        // What each shape plans to today. A later build may plan faster and must still
        // plan to these: a saved result holds them, and a table fails on any other.
        let leaves: Vec<u64> = run.shapes.each().iter().map(|shape| shape.leaves).collect();
        assert_eq!(leaves, [1_360, 4_460, 1_005, 10_000]);
        for shape in run.shapes.each() {
            assert_eq!(shape.ms.len(), 2);
            assert!(shape.ms.iter().all(|ms| *ms > 0.0), "{:?}", shape.ms);
            assert_eq!(
                shape.p50_ms,
                percentile(&shape.ms, 0.50).expect("two timings")
            );
            assert_eq!(
                shape.p99_ms,
                percentile(&shape.ms, 0.99).expect("two timings")
            );
            assert!(shape.min_ms <= shape.p50_ms && shape.p50_ms <= shape.p99_ms);
        }
    }

    /// A line as the child prints it: what `measure` returns, through serde, and a line
    /// feed.
    fn printed(run: &PlanRun) -> Vec<u8> {
        format!(
            "{}\n",
            serde_json::to_string(run).expect("a plan run is JSON")
        )
        .into_bytes()
    }

    fn a_run(samples: usize) -> PlanRun {
        let shape = |ms: f64, leaves: u64| PlanShape {
            ms: vec![ms; samples],
            p50_ms: ms,
            p99_ms: ms,
            min_ms: ms,
            leaves,
        };
        PlanRun {
            templates: TEMPLATES,
            nodes: 57_642,
            tokens: 98_495,
            lines_skipped: 0,
            shapes: Shapes {
                p1: shape(4.58, 1_360),
                p2: shape(16.2, 4_460),
                p3: shape(14.4, 1_005),
                p4: shape(17.9, 10_000),
            },
        }
    }

    #[test]
    fn the_childs_one_line_reads_back_as_what_it_measured() {
        let run = a_run(3);
        let line = printed(&run);
        assert_eq!(line.iter().filter(|byte| **byte == b'\n').count(), 1);
        assert_eq!(read_line(&line, 3), Ok(run));
    }

    #[test]
    fn anything_but_that_one_line_is_said_in_a_sentence() {
        let wrong = |stdout: &[u8], samples| read_line(stdout, samples).expect_err("refused");

        assert_eq!(
            wrong(b"", 3),
            "it printed 0 lines where one line of JSON is read"
        );
        let mut twice = printed(&a_run(3));
        twice.extend(printed(&a_run(3)));
        assert_eq!(
            wrong(&twice, 3),
            "it printed 2 lines where one line of JSON is read"
        );
        assert!(
            wrong(b"bench --plan-only\n", 3).starts_with("its line is not the plan step's JSON (")
        );
        assert!(wrong(&[0xff, b'\n'], 3).starts_with("its standard output is not UTF-8 ("));

        // Timings of another trie, or fewer of them than were asked for, are not this
        // run's plan step.
        let mut other = a_run(3);
        other.templates = 9_999;
        assert_eq!(
            wrong(&printed(&other), 3),
            "it planned on a trie of 9,999 templates where the plan step's has 10,000"
        );
        assert_eq!(
            wrong(&printed(&a_run(3)), 100),
            "it timed P1 3 times where 100 were asked for"
        );
    }

    #[test]
    fn a_shape_is_its_timings_and_the_one_leaf_count_every_plan_returned() {
        let kept = shape("P2", vec![3.0, 1.0, 2.0], &[7, 7, 7]).expect("a shape");
        assert_eq!(kept.ms, [3.0, 1.0, 2.0], "in the order taken");
        assert_eq!((kept.p50_ms, kept.p99_ms, kept.min_ms), (2.0, 3.0, 1.0));
        assert_eq!(kept.leaves, 7);

        let moved = shape("P2", vec![1.0, 1.0], &[7, 8]).expect_err("two counts");
        assert_eq!(
            moved.to_string(),
            "engine::plan did not answer the way kibbr bench reads it: P2 planned to 7 \
             leaves and then to 8 on the same trie"
        );
        let none = shape("P2", Vec::new(), &[]).expect_err("no timing");
        assert!(
            none.to_string().contains("P2 was planned no times"),
            "{none}"
        );
    }

    #[test]
    fn the_arrival_time_is_noon_of_the_farms_day() {
        assert_eq!(arrival().to_rfc3339(), "2024-01-15T12:00:00+00:00");
    }

    /// A directory for one test's child, removed when the test ends.
    struct Scratch(std::path::PathBuf);

    impl Scratch {
        fn new(name: &str) -> Self {
            let dir = std::env::temp_dir()
                .join(format!("kibbr-speed-plan-{}-{name}", std::process::id()));
            let _ = fs::remove_dir_all(&dir);
            fs::create_dir_all(&dir).expect("a scratch directory");
            Self(dir)
        }
    }

    impl Drop for Scratch {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[cfg(unix)]
    #[test]
    fn a_child_that_fails_or_prints_something_else_is_named_with_where_its_words_are() {
        let scratch = Scratch::new("child");

        // `echo` exits 0 and prints its arguments: one line, and not the plan step's.
        let echoed = child(Path::new("/bin/echo"), 3, &scratch.0).expect_err("not JSON");
        let SpeedError::Child { what, code, stderr } = &echoed else {
            panic!("{echoed:?}");
        };
        assert_eq!((*what, *code), ("kibbr bench --plan-only", Some(0)));
        assert!(
            stderr.starts_with("its line is not the plan step's JSON ("),
            "{stderr}"
        );
        assert!(
            stderr.contains("; its standard error is kept in "),
            "{stderr}"
        );

        // A child that exits 1 having written to standard error is quoted from the file.
        let failed = child(Path::new("/bin/ls"), 3, &scratch.0).expect_err("ls refuses the flags");
        let SpeedError::Child { code, stderr, .. } = &failed else {
            panic!("{failed:?}");
        };
        assert_ne!(*code, Some(0));
        assert!(
            stderr.contains("plan-") && stderr.contains(".log and ends:\n"),
            "{stderr}"
        );
        assert!(
            stderr.lines().count() >= 2,
            "ls said why, and it is quoted: {stderr}"
        );

        // Each child's standard error is a file of its own.
        let logs = fs::read_dir(&scratch.0).expect("the scratch").count();
        assert_eq!(logs, 2);
    }
}
