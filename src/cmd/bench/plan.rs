//! The plan step - which templates a query must read - timed on a trie of 10,000
//! templates.
//!
//! This file holds the building of that trie, the timed plans of four query shapes on it,
//! the one JSON line `kibbr bench --plan-only` prints, and the child process a run starts
//! for them, whose line is read back here.
//!
//! **A trie of its own.** The farm has 145 templates at a million lines and cannot have
//! 10,000, so the plan step cannot be read off the loaded directory. The trie here is the
//! older generator's, whose keys the measuring script's four texts were written for: the
//! shapes are those texts, unchanged.
//!
//! **A process of its own.** A plan allocates for every node it crosses, so it is timed
//! where the heap holds the trie and nothing else, on one thread, under the allocator the
//! server runs under, with no server alive. Building the trie warns for each template
//! without a time column and each column that widens, hundreds of lines, which is why the
//! child's standard error is a file.

